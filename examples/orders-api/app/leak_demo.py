"""DEMO FAULT: a background task that reproduces the production memory leak on demand.

This module exists so the incident can be replayed in a lab. It is NOT part of the
business logic. When the process is started with `LEAK=1` (or `--leak`), a background
task creates a synthetic order every `LEAK_INTERVAL_S` seconds whose payload is
`LEAK_STEP_MB` megabytes, and hands it to `app.orders.service.create_order`, which in
turn calls `app.orders.cache.remember`. Because `ORDER_CACHE` never evicts, every step
adds LEAK_STEP_MB to the resident set until the kernel OOM killer stops the service.

The task logs "gradual leak started" once and then "order cache grew" after every step,
with rss_mb / held_mb / mem_available_pct on each line, exactly like production did.

The leak itself is in app/orders/cache.py. This file only exercises it faster.
"""
from __future__ import annotations

import asyncio
import logging
import os

from app.logging_config import memory_snapshot
from app.orders import cache
from app.orders.models import OrderCreate, OrderLine
from app.orders.service import create_order

log = logging.getLogger("orders-api.leak_demo")

LEAK_STEP_MB = int(os.environ.get("LEAK_STEP_MB", "20"))
LEAK_INTERVAL_S = float(os.environ.get("LEAK_INTERVAL_S", "5"))
LEAK_MAX_STEPS = int(os.environ.get("LEAK_MAX_STEPS", "0"))  # 0 == until killed


def leak_enabled() -> bool:
    return os.environ.get("LEAK", "").strip().lower() in {"1", "true", "yes", "on"}


def _synthetic_order(step: int) -> OrderCreate:
    return OrderCreate(
        customer_id=f"synthetic-{step:06d}",
        lines=[OrderLine(sku="DEMO-LEAK", quantity=1, unit_price_cents=0)],
        note="synthetic order generated by leak_demo",
    )


def _log_growth(step: int) -> None:
    snap = memory_snapshot()
    stats = cache.cache_stats()
    log.warning(
        "order cache grew",
        extra={
            "rss_mb": snap["rss_mb"],
            "held_mb": stats["held_mb"],
            "mem_available_pct": snap["mem_available_pct"],
        },
    )
    log.debug("leak step %d: cache entries=%d", step, stats["entries"])


async def run_leak(step_mb: int = LEAK_STEP_MB, interval_s: float = LEAK_INTERVAL_S, max_steps: int = LEAK_MAX_STEPS) -> int:
    """Grow the order cache by `step_mb` every `interval_s` seconds. Returns steps taken."""
    log.warning("gradual leak started")
    step = 0
    while max_steps <= 0 or step < max_steps:
        step += 1
        payload = bytes(step_mb * 1024 * 1024)  # a real allocation, not a view
        create_order(_synthetic_order(step), payload=payload)
        _log_growth(step)
        await asyncio.sleep(interval_s)
    return step


def start_leak_task(loop: asyncio.AbstractEventLoop | None = None) -> asyncio.Task[int]:
    loop = loop or asyncio.get_event_loop()
    return loop.create_task(run_leak(), name="leak_demo")
